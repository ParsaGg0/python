# برنامه بررسی شرایط دریافت وام بانک شهر هوشمند

# دریافت میانگین موجودی 6 ماه اخیر از کاربر
miyangin = float(input("میانگین موجودی 6 ماه اخیر خود را وارد کنید: "))

# بررسی شرایط
if miyangin > 50000000:
    print("✅ شما واجد شرایط دریافت وام هستید.")
else:
    print("❌ متاسفانه شرایط لازم برای دریافت وام را ندارید.")